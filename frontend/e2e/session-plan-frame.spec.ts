import { expect, test } from "@playwright/test";
import { installFakeAgent } from "./support/fake-bridge";

test("session Plan floats without moving Chat, restores preferences and hard-fits above the composer @T0", async ({ page }) => {
	const sessionId = "session-plan-frame";
	const now = "2026-10-28T12:00:00Z";
	await page.setViewportSize({ width: 1440, height: 900 });
	await installFakeAgent(page, { workers: [{ id: sessionId, title: "A long session with a persistent Plan", mode: "chat" }] });
	await page.route(`**/api/v1/sessions/${sessionId}/**`, async (route) => {
		const path = new URL(route.request().url()).pathname;
		if (path.endsWith("/plan")) await route.fulfill({ json: { state: "present", conversationId: "plan-conversation", activeBranchId: "root", version: { branchId: "root", turnId: "old-turn", sourceActivityId: "old-plan", sequence: 2, revision: 3, updatedAt: now, plan: { spansTurns: true, steps: [{ text: "Plan from outside the loaded page", status: "in_progress" }] } } } });
		else if (path.endsWith("/conversation")) await route.fulfill({ json: { conversationId: "plan-conversation", sessionId, harness: "claude-code", mode: "chat", controller: "ready", settings: {}, oldestSequence: 250, latestSequence: 251, hasMoreBefore: false, turns: [{ id: "recent", state: "completed", requestedAt: now }], messages: [{ kind: "message", id: "recent-message", turnId: "recent", sequence: 250, revision: 0, role: "user", origin: "human", text: "A recent message without the old Plan", streaming: false, createdAt: now }], activities: [] } });
		else if (path.endsWith("/conversation/models")) await route.fulfill({ json: { models: [], selected: {} } });
		else if (path.endsWith("/conversation/skills")) await route.fulfill({ json: { skills: [] } });
		else if (path.endsWith("/workspace/files")) await route.fulfill({ json: { files: [], truncated: false } });
		else await route.fulfill({ status: 404, json: { error: { code: "NOT_FOUND", message: "not found" } } });
	});
	await page.goto(`/#/projects/fake-proj/sessions/${sessionId}`);
	const entry = page.getByRole("button", { name: "Plan 0/1", expanded: false });
	await expect(entry).toBeVisible();
	const composer = page.locator(".cursor-chat-composer-dock");
	const before = await composer.boundingBox();
	await entry.click();
	const frame = page.getByRole("region", { name: "Plan", exact: true });
	await expect(frame.getByText("Plan from outside the loaded page")).toBeVisible();
	expect(await composer.boundingBox()).toEqual(before);
	const transcript = page.getByRole("log", { name: "Conversation" });
	await expect(transcript.getByText("Plan from outside the loaded page")).toHaveCount(0);
	const fits = async () => {
		const f = await frame.boundingBox(); const c = await composer.boundingBox();
		expect(f).not.toBeNull(); expect(c).not.toBeNull();
		if (!f || !c) throw new Error("Missing frame or composer geometry");
		expect(f.y + f.height).toBeLessThanOrEqual(c.y - 15);
	};
	await fits();
	const width = await frame.evaluate((node) => node.getBoundingClientRect().width);
	await frame.getByRole("separator", { name: "Resize Plan width" }).press("ArrowLeft");
	await expect.poll(() => frame.evaluate((node) => node.getBoundingClientRect().width)).toBe(width + 16);
	await page.reload();
	await expect(frame).toBeVisible();
	await expect.poll(() => frame.evaluate((node) => node.getBoundingClientRect().width)).toBe(width + 16);
	await fits();
	await page.setViewportSize({ width: 900, height: 350 });
	await expect(frame).not.toBeVisible();
	await page.getByRole("button", { name: "Open Plan", exact: true }).click();
	const compact = page.getByRole("dialog", { name: "Plan", exact: true });
	await expect(compact).toBeVisible();
	const compactRect = await compact.boundingBox(); const dockRect = await composer.boundingBox();
	if (!compactRect || !dockRect) throw new Error("Missing compact geometry");
	expect(compactRect.y + compactRect.height).toBeLessThanOrEqual(dockRect.y - 15);
	await compact.getByRole("button", { name: "Collapse Plan" }).click();
	await page.setViewportSize({ width: 1440, height: 900 });
	await expect(frame).toBeVisible();
	await frame.getByRole("button", { name: "Collapse Plan" }).click();
	await page.reload();
	await expect(entry).toBeVisible();
});
